    /**
     * Polimorfna metoda koja vraća adaptiranu uslugu kao objekat tipa Komponenta.
     */
    @Override
    public Komponenta getValue() throws Exception {
        clearError();

        String naziv = txtNaziv.getText().trim();
        String opis = txtOpisAktivnosti.getText().trim();
        String serviser = txtServiser.getText().trim();
        String cenaStr = txtCenaBezPDV.getText().trim();
        String pdvStr = txtStopaPDV.getText().trim();

        if (naziv.isEmpty()) {
            lblError.setText("Polje 'Naziv usluge' je obavezno!");
            txtNaziv.requestFocus();
            throw new Exception("Polje 'Naziv usluge' je obavezno!");
        }

        if (opis.isEmpty()) {
            lblError.setText("Polje 'Opis aktivnosti' je obavezno!");
            txtOpisAktivnosti.requestFocus();
            throw new Exception("Polje 'Opis aktivnosti' je obavezno!");
        }

        if (serviser.isEmpty()) {
            lblError.setText("Polje 'Serviser' je obavezno!");
            txtServiser.requestFocus();
            throw new Exception("Polje 'Serviser' je obavezno!");
        }

        if (cenaStr.isEmpty()) {
            lblError.setText("Polje 'Cena bez PDV-a' je obavezno!");
            txtCenaBezPDV.requestFocus();
            throw new Exception("Polje 'Cena bez PDV-a' je obavezno!");
        }

        if (pdvStr.isEmpty()) {
            lblError.setText("Polje 'Stopa PDV-a' je obavezno!");
            txtStopaPDV.requestFocus();
            throw new Exception("Polje 'Stopa PDV-a' je obavezno!");
        }

        double cenaBezPdv;
        double stopaPdv;

        try {
            cenaBezPdv = Double.parseDouble(cenaStr.replace(",", "."));
            if (cenaBezPdv <= 0) {
                lblError.setText("Cena mora biti veća od nule!");
                txtCenaBezPDV.requestFocus();
                throw new Exception("Cena mora biti veća od nule!");
            }
        } catch (NumberFormatException ex) {
            lblError.setText("Neispravan numerički format za cenu!");
            txtCenaBezPDV.requestFocus();
            throw new Exception("Neispravan numerički format za cenu!");
        }

        try {
            stopaPdv = Double.parseDouble(pdvStr.replace(",", "."));
            if (stopaPdv < 0) {
                lblError.setText("Stopa PDV-a ne može biti negativna!");
                txtStopaPDV.requestFocus();
                throw new Exception("Stopa PDV-a ne može biti negativna!");
            }
        } catch (NumberFormatException ex) {
            lblError.setText("Neispravan numerički format za stopu PDV-a!");
            txtStopaPDV.requestFocus();
            throw new Exception("Neispravan numerički format za stopu PDV-a!");
        }

        // 1. Kreiramo uslugu iz servisnog podsistema (Adaptee)
        Usluga usluga = new InstalacionaUsluga(naziv, opis, serviser, cenaBezPdv, stopaPdv);

        // 2. Vraćamo adapter koji implementira Komponenta (Target)
        return new UslugaAdapter(usluga);
    }

    @Override
    public void clearError() {
        lblError.setText(" ");
    }

    @Override
    public void reset() {
        txtNaziv.setText("");
        txtOpisAktivnosti.setText("");
        txtServiser.setText("");
        txtCenaBezPDV.setText("");
        txtStopaPDV.setText("20");
        clearError();
    }

    /**
     * Pomoćna metoda za postavljanje podataka (demo ili izmena).
     */
    public void postaviPodatke(String naziv, String opis, String serviser, double cenaBezPdv, double stopaPdv) {
        txtNaziv.setText(naziv);
        txtOpisAktivnosti.setText(opis);
        txtServiser.setText(serviser);
        txtCenaBezPDV.setText(String.format("%.2f", cenaBezPdv));
        txtStopaPDV.setText(String.format("%.1f", stopaPdv));
        clearError();
    }

