    @Override
    public Komponenta getValue() throws Exception {
        clearError();

        String naziv = txtNaziv.getText().trim();
        String specifikacija = txtSpecifikacija.getText().trim();
        String dobavljac = txtDobavljac.getText().trim();
        String cenaStr = txtCena.getText().trim();

        if (naziv.isEmpty()) {
            lblError.setText("Polje 'Naziv komponente' je obavezno!");
            txtNaziv.requestFocus();
            throw new Exception("Polje 'Naziv komponente' je obavezno!");
        }

        if (specifikacija.isEmpty()) {
            lblError.setText("Polje 'Specifikacija' je obavezno!");
            txtSpecifikacija.requestFocus();
            throw new Exception("Polje 'Specifikacija' je obavezno!");
        }

        if (dobavljac.isEmpty()) {
            lblError.setText("Polje 'Dobavljač' je obavezno!");
            txtDobavljac.requestFocus();
            throw new Exception("Polje 'Dobavljač' je obavezno!");
        }

        if (cenaStr.isEmpty()) {
            lblError.setText("Polje 'Prodajna cena' je obavezno!");
            txtCena.requestFocus();
            throw new Exception("Polje 'Prodajna cena' je obavezno!");
        }

        double cena;
        try {
            cena = Double.parseDouble(cenaStr.replace(",", "."));
            if (cena <= 0) {
                lblError.setText("Prodajna cena mora biti veća od nule!");
                txtCena.requestFocus();
                throw new Exception("Prodajna cena mora biti veća od nule!");
            }
        } catch (NumberFormatException ex) {
            lblError.setText("Neispravan numerički format za cenu!");
            txtCena.requestFocus();
            throw new Exception("Neispravan numerički format za cenu!");
        }

        return new HardverskaKomponenta(naziv, specifikacija, dobavljac, cena);
    }

    @Override
    public void clearError() {
        lblError.setText(" ");
    }

    @Override
    public void reset() {
        txtNaziv.setText("");
        txtSpecifikacija.setText("");
        txtDobavljac.setText("");
        txtCena.setText("");
        clearError();
    }

    /**
     * Postavlja vrednosti u polja (korisno za demo ili izmenu).
     */
    public void postaviPodatke(String naziv, String spec, String dobavljac, double cena) {
        txtNaziv.setText(naziv);
        txtSpecifikacija.setText(spec);
        txtDobavljac.setText(dobavljac);
        txtCena.setText(String.format("%.2f", cena));
        clearError();
    }

