    private void osveziPrikaz() {
        tableModel.setRowCount(0);
        int rb = 1;

        for (Komponenta k : podsistem.getProdateStavke()) {
            String tip = (k instanceof UslugaAdapter) ? "Usluga (Adapter)" : "Hardver";
            String spec = k.dajSpecifikaciju();
            String dobavljac = k.dajDobavljaca();
            String cena = String.format("%,.2f", k.dajProdajnuCijenu());

            tableModel.addRow(new Object[]{rb++, tip, spec, dobavljac, cena});
        }

        lblUkupno.setText(String.format("Ukupan iznos: %,.2f RSD", podsistem.izracunajUkupnuProdajnuCijenu()));
    }

