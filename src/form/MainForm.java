    private void btnDodajKomponentuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajKomponentuActionPerformed
        String naziv = txtNaziv.getText().trim();
        String dobavljac = txtDobavljac.getText().trim();
        String cenaStr = txtCena.getText().trim();

        if (naziv.isEmpty() || dobavljac.isEmpty() || cenaStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Sva polja za komponentu su obavezna!", "Upozorenje", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double cena = Double.parseDouble(cenaStr);
            if (cena <= 0) {
                JOptionPane.showMessageDialog(this, "Cena mora biti veća od nule!", "Upozorenje", JOptionPane.WARNING_MESSAGE);
                return;
            }

            Komponenta k = new HardverskaKomponenta(naziv, dobavljac, cena);
            podsistem.dodajProdatuKomponentu(k);

            txtNaziv.setText("");
            txtDobavljac.setText("");
            txtCena.setText("");

            osveziPrikaz();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Cena mora biti validan broj!", "Greška", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnDodajKomponentuActionPerformed

    private void btnDodajUsluguActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajUsluguActionPerformed
        String opis = txtOpis.getText().trim();
        String serviser = txtServiser.getText().trim();
        String cenaBezPdvStr = txtCenaBezPdv.getText().trim();
        String pdvStr = txtPdv.getText().trim();

        if (opis.isEmpty() || serviser.isEmpty() || cenaBezPdvStr.isEmpty() || pdvStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Sva polja za uslugu su obavezna!", "Upozorenje", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double cenaBezPdv = Double.parseDouble(cenaBezPdvStr);
            double pdv = Double.parseDouble(pdvStr);

            if (cenaBezPdv <= 0 || pdv < 0) {
                JOptionPane.showMessageDialog(this, "Cena mora biti veća od nule, a PDV nenegativan!", "Upozorenje", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Kreiramo originalnu instancu servisa (Adaptee)
            Usluga usluga = new InstalacionaUsluga(opis, serviser, cenaBezPdv, pdv);

            // KLJUČNI KORAK - PROJEKTNI UZOR ADAPTER:
            // Obavijamo Usluga objekat u UslugaAdapter koji implementira Komponenta interfejs
            Komponenta adapter = new UslugaAdapter(usluga);

            // Maloprodajni podsistem prihvata adapter jer radi isključivo sa interfejsom Komponenta
            podsistem.dodajProdatuKomponentu(adapter);

            txtOpis.setText("");
            txtServiser.setText("");
            txtCenaBezPdv.setText("");
            txtPdv.setText("20");

            osveziPrikaz();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Cena i PDV moraju biti validni brojevi!", "Greška", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnDodajUsluguActionPerformed

